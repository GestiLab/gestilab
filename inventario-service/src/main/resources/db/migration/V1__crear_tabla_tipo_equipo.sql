-- SCRUM-6 · RQ-01 Modificabilidad
-- Las reglas de préstamo viven como DATOS del tipo de equipo, nunca como condicionales en el código.
-- Compatible con PostgreSQL y H2 (modo PostgreSQL).
CREATE TABLE tipo_equipo (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                       VARCHAR(100) NOT NULL,
    descripcion                  VARCHAR(500),
    duracion_maxima_dias         INTEGER      NOT NULL,
    requiere_autorizacion_previa BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_tipo_equipo_duracion_positiva CHECK (duracion_maxima_dias > 0)
);
